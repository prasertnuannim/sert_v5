import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const schemaUrl = process.env.OPENAPI_URL ?? 'http://localhost:5178/openapi/v1.json'
const outputPath = path.resolve('src/api/schema.d.ts')
const response = await fetch(schemaUrl)

if (!response.ok) {
  throw new Error(`Unable to load OpenAPI schema: ${response.status} ${response.statusText}`)
}

const document = await response.json()
const schemas = document.components?.schemas ?? {}

function typeOf(schema = {}) {
  if (schema.$ref) return schema.$ref.split('/').at(-1)
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')

  const variants = schema.oneOf ?? schema.anyOf
  if (variants) return variants.map(typeOf).join(' | ')

  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => typeOf({ ...schema, type })).join(' | ')
  }

  switch (schema.type) {
    case 'array':
      return `Array<${typeOf(schema.items)}>`
    case 'boolean':
      return 'boolean'
    case 'integer':
    case 'number':
      return 'number'
    case 'object':
      if (schema.additionalProperties) {
        return `Record<string, ${typeOf(schema.additionalProperties)}>`
      }
      return 'Record<string, unknown>'
    case 'null':
      return 'null'
    case 'string':
      return 'string'
    default:
      return 'unknown'
  }
}

function propertyName(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
}

const declarations = Object.entries(schemas).map(([name, schema]) => {
  if (schema.type !== 'object' || !schema.properties) {
    return `export type ${name} = ${typeOf(schema)}`
  }

  const required = new Set(schema.required ?? [])
  const properties = Object.entries(schema.properties).map(
    ([property, propertySchema]) =>
      `  ${propertyName(property)}${required.has(property) ? '' : '?'}: ${typeOf(propertySchema)}`,
  )

  return `export interface ${name} {\n${properties.join('\n')}\n}`
})

const output = `/**
 * Generated from ${schemaUrl}.
 * Do not edit this file directly; run npm run generate:api.
 */

${declarations.join('\n\n')}
`

await mkdir(path.dirname(outputPath), { recursive: true })
await writeFile(outputPath, output)
console.log(`Generated ${path.relative(process.cwd(), outputPath)}`)
